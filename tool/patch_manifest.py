import re, os, glob, shutil

APP_LABEL = "Educational Center"   # اسم التطبيق على الموبايل — غيّره براحتك
PACKAGE = "com.mohamed.educenter"
CHANNEL_ID = "edu_high"            # لازم يطابق channelId في functions/index.js

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android/app/src/main/res")
MANIFEST = os.path.join(ROOT, "android/app/src/main/AndroidManifest.xml")

# ---------- 1) Manifest: permissions + notification meta-data + label ----------
s = open(MANIFEST, encoding="utf-8").read()

perms = """
    <uses-permission android:name="android.permission.INTERNET"/>
    <uses-permission android:name="android.permission.ACCESS_NETWORK_STATE"/>
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS"/>
    <uses-permission android:name="android.permission.VIBRATE"/>
    <uses-permission android:name="android.permission.RECORD_AUDIO"/>
    <uses-permission android:name="android.permission.MODIFY_AUDIO_SETTINGS"/>
    <uses-permission android:name="android.permission.CAMERA"/>
    <uses-permission android:name="android.permission.READ_MEDIA_IMAGES"/>
    <uses-permission android:name="android.permission.READ_MEDIA_VIDEO"/>
    <uses-permission android:name="android.permission.READ_MEDIA_AUDIO"/>
    <uses-permission android:name="android.permission.READ_EXTERNAL_STORAGE" android:maxSdkVersion="32"/>
    <uses-permission android:name="android.permission.WRITE_EXTERNAL_STORAGE" android:maxSdkVersion="29"/>
    <uses-feature android:name="android.hardware.camera" android:required="false"/>
    <uses-feature android:name="android.hardware.microphone" android:required="false"/>
"""
if "READ_MEDIA_IMAGES" not in s:
    s = re.sub(r"(<manifest[^>]*>)", lambda m: m.group(1) + perms, s, count=1)

# label + launcher icon
s = re.sub(r'android:label="[^"]*"', 'android:label="%s"' % APP_LABEL, s, count=1)
s = re.sub(r'android:icon="[^"]*"', 'android:icon="@mipmap/ic_launcher"', s, count=1)
if "android:roundIcon" not in s:
    s = s.replace('android:icon="@mipmap/ic_launcher"',
                  'android:icon="@mipmap/ic_launcher"\n        android:roundIcon="@mipmap/ic_launcher_round"', 1)

meta = """
        <meta-data android:name="com.google.firebase.messaging.default_notification_channel_id"
                   android:value="%s"/>
        <meta-data android:name="com.google.firebase.messaging.default_notification_icon"
                   android:resource="@drawable/ic_stat_notify"/>
        <meta-data android:name="com.google.firebase.messaging.default_notification_color"
                   android:resource="@color/notif_color"/>
""" % CHANNEL_ID
if "default_notification_channel_id" not in s:
    s = s.replace("</application>", meta + "    </application>", 1)
open(MANIFEST, "w", encoding="utf-8").write(s)

# ---------- 2) Icons (launcher / adaptive / notification) ----------
icons = os.path.join(ROOT, "tool/icons")
for d in glob.glob(os.path.join(icons, "mipmap-*")) + glob.glob(os.path.join(icons, "drawable-*")):
    dst = os.path.join(RES, os.path.basename(d))
    os.makedirs(dst, exist_ok=True)
    for f in os.listdir(d):
        shutil.copy2(os.path.join(d, f), os.path.join(dst, f))

# adaptive icon (Android 8+): white background + logo foreground
os.makedirs(os.path.join(RES, "mipmap-anydpi-v26"), exist_ok=True)
adaptive = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
"""
for n in ("ic_launcher.xml", "ic_launcher_round.xml"):
    open(os.path.join(RES, "mipmap-anydpi-v26", n), "w", encoding="utf-8").write(adaptive)

os.makedirs(os.path.join(RES, "values"), exist_ok=True)
open(os.path.join(RES, "values/edu_colors.xml"), "w", encoding="utf-8").write("""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">#FFFFFF</color>
    <color name="notif_color">#3FA535</color>
</resources>
""")

# ---------- 3) MainActivity: create HIGH-importance channel with the phone's DEFAULT notification sound ----------
kt_dir = os.path.join(ROOT, "android/app/src/main/kotlin", *PACKAGE.split("."))
os.makedirs(kt_dir, exist_ok=True)
# remove any other MainActivity generated by the template
for f in glob.glob(os.path.join(ROOT, "android/app/src/main/**/MainActivity.*"), recursive=True):
    os.remove(f)
open(os.path.join(kt_dir, "MainActivity.kt"), "w", encoding="utf-8").write("""package %(pkg)s

import android.app.NotificationChannel
import android.app.NotificationManager
import android.media.AudioAttributes
import android.media.RingtoneManager
import android.os.Build
import android.os.Bundle
import io.flutter.embedding.android.FlutterActivity

class MainActivity : FlutterActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        createChannel()
    }

    private fun createChannel() {
        if (Build.VERSION.SDK_INT < Build.VERSION_CODES.O) return
        val nm = getSystemService(NotificationManager::class.java) ?: return
        val ch = NotificationChannel("%(ch)s", "الإشعارات", NotificationManager.IMPORTANCE_HIGH)
        ch.description = "إشعارات السنتر"
        ch.enableVibration(true)
        ch.enableLights(true)
        ch.setShowBadge(true)
        // صوت الإشعار الافتراضي بتاع الموبايل نفسه
        ch.setSound(
            RingtoneManager.getDefaultUri(RingtoneManager.TYPE_NOTIFICATION),
            AudioAttributes.Builder()
                .setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION)
                .setUsage(AudioAttributes.USAGE_NOTIFICATION)
                .build()
        )
        nm.createNotificationChannel(ch)
    }
}
""" % {"pkg": PACKAGE, "ch": CHANNEL_ID})

print("manifest + icons + MainActivity patched")
